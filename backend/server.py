@api_router.post("/library/locations/sync")
async def sync_library_locations(payload: LibrarySyncPayload):
    """Upsert location metadata harvested from the itinerary index. Existing
    Library images/notes are preserved; brand-new locations are seeded with
    their default programmatic gallery so the Library is never empty."""
    if not payload.locations:
        return {"synced": 0, "created": 0}
    now = datetime.now(timezone.utc).isoformat()
    ops = []
    for loc in payload.locations[:5000]:
        lid = (loc.id or "").strip()
        if not lid:
            continue
        seed_imgs = []
        for i, url in enumerate(loc.seedImages[:40]):
            if isinstance(url, str) and url.strip():
                seed_imgs.append({
                    "id": uuid.uuid4().hex,
                    "url": url,
                    "storage_path": None,
                    "caption": (loc.seedCaptions[i] if i < len(loc.seedCaptions) else "") or "",
                    "source": "seed",
                })
        ops.append(UpdateOne(
            {"_id": lid},
            {
                "$set": {
                    "name": loc.name or {},
                    "kind": loc.kind,
                    "zone": loc.zone,
                    "group": loc.group,
                    "lat": loc.lat,
                    "lng": loc.lng,
                    "trips": loc.trips or [],
                    "updated_at": now,
                },
                "$setOnInsert": {
                    "images": seed_imgs,
                    "notes": "",
                    "indexed_at": now,
                },
            },
            upsert=True,
        ))
    created = 0
    if ops:
        res = await db.library_locations.bulk_write(ops, ordered=False)
        created = res.upserted_count or 0
    return {"synced": len(ops), "created": created}


@api_router.put("/library/locations/{location_id}")
async def update_library_location(location_id: str, payload: LibraryLocationPayload):
    update: Dict[str, Any] = {"updated_at": datetime.now(timezone.utc).isoformat()}
    if payload.images is not None:
        imgs = []
        for im in payload.images[:200]:
            if not im.url:
                continue
            imgs.append({
                "id": im.id or uuid.uuid4().hex,
                "url": im.url,
                "storage_path": im.storage_path,
                "caption": (im.caption or "")[:1000],
                "source": im.source,
            })
        update["images"] = imgs
    if payload.notes is not None:
        update["notes"] = payload.notes[:5000]
    for f in ("name", "kind", "zone", "group", "trips"):
        v = getattr(payload, f)
        if v is not None:
            update[f] = v
    await db.library_locations.update_one({"_id": location_id}, {"$set": update}, upsert=True)
    doc = await db.library_locations.find_one({"_id": location_id})
    if doc:
        doc["id"] = doc.pop("_id")
    return doc or {"id": location_id, **update}


@api_router.post("/translate")
async def translate_text(body: TranslateBody):
    """Translate a short CMS string from `source` into each of `targets`.
    Returns { "translations": { "en": "...", "fr": "..." } }. One LLM call
    returns all targets as JSON to keep latency low."""
    text = (body.text or "").strip()
    targets = [t for t in body.targets if t in ("en", "fr", "es") and t != body.source]
    if not text or not targets:
        return {"translations": {}}
    if not EMERGENT_LLM_KEY:
        raise HTTPException(503, "Translation service not configured")

    from emergentintegrations.llm.chat import LlmChat, UserMessage

    target_desc = ", ".join(f'"{t}" ({LANG_NAMES[t]})' for t in targets)
    json_shape = ", ".join(f'"{t}": "..."' for t in targets)
    system = (
        "You are a professional translator for a premium Moroccan travel agency website. "
        "Translate faithfully, preserving the marketing tone, proper nouns, place names and "
        "inline punctuation. Do not add or remove information. "
        "Return ONLY a strict JSON object, no markdown, no commentary."
    )
    prompt = (
        f"Source language: {LANG_NAMES.get(body.source, body.source)}.\n"
        f"Translate the text into: {target_desc}.\n"
        f"Return strictly a JSON object like {{{json_shape}}}.\n\n"
        f"TEXT:\n{text}"
    )
    try:
        chat = LlmChat(
            api_key=EMERGENT_LLM_KEY,
            session_id=f"cms-translate-{uuid.uuid4().hex}",
            system_message=system,
        ).with_model("openai", "gpt-4o-mini")
        resp = await chat.send_message(UserMessage(text=prompt))
    except Exception as e:
        logger.error(f"translate failed: {e}")
        raise HTTPException(502, "Translation provider error")

    out: Dict[str, str] = {}
    try:
        m = re.search(r"\{.*\}", resp, re.S)
        data = _json.loads(m.group(0)) if m else {}
        for t in targets:
            val = data.get(t)
            if val:
                out[t] = str(val).strip()
    except Exception as e:
        logger.error(f"translate parse failed: {e} | raw={resp[:200]}")
    return {"translations": out}


