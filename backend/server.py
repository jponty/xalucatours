# --- Encoder tuning (env-configurable) -----------------------------------
# Quality is shared by on-the-fly and warm/offline encodes; the encode EFFORT
# differs: on-the-fly favours latency (fast), warm favours smaller files (slow,
# paid only once because variants are cached on disk).
def _env_int(name, default):
    try:
        return int(os.environ.get(name, default))
    except (TypeError, ValueError):
        return default

AVIF_QUALITY = _env_int("IMG_AVIF_QUALITY", 55)        # ~visually lossless for photos
WEBP_VARIANT_QUALITY = _env_int("IMG_WEBP_QUALITY", 80)
AVIF_SPEED_ONTHEFLY = _env_int("IMG_AVIF_SPEED", 8)    # 0=best/slowest … 10=fastest
AVIF_SPEED_WARM = _env_int("IMG_AVIF_SPEED_WARM", 6)   # slower → ~10-15% smaller, cached once
WEBP_METHOD_ONTHEFLY = _env_int("IMG_WEBP_METHOD", 4)  # 0=fast … 6=best
WEBP_METHOD_WARM = _env_int("IMG_WEBP_METHOD_WARM", 6)


def _encode_variant(data, content_type, width, target, mime_map):
    """CPU-bound: decode → optional downscale → re-encode to the target
    modern format. Runs in a worker thread (asyncio.to_thread) so a burst
    of first-time AVIF/WebP encodes never blocks the event loop.

    Returns (bytes, mime, ext, cacheable). On any Pillow failure it returns
    the untouched original (ext='orig', cacheable=False) so an <img> never
    breaks because of optimisation."""
    try:
        img = Image.open(BytesIO(data))
        # Fast-path huge JPEGs: ask the decoder for a reduced-scale raster
        # (1/2, 1/4, 1/8) near the target width — slashes decode time on
        # multi-MB originals before the precise LANCZOS downscale. No-op for
        # non-JPEG sources.
        if width:
            try:
                img.draft(None, (width, width))
            except Exception:
                pass
        img.load()
        # Downscale only (never upscale) to preserve sharpness.
        if width and img.width > width:
            new_h = max(1, round(img.height * width / img.width))
            img = img.resize((width, new_h), Image.LANCZOS)

        save_fmt = {"avif": "AVIF", "webp": "WEBP"}.get(target)
        out = BytesIO()
        if save_fmt in ("WEBP", "AVIF"):
            if img.mode not in ("RGB", "RGBA"):
                img = img.convert("RGBA" if "A" in img.getbands() else "RGB")
            if save_fmt == "AVIF":
                # AVIF at this quality is perceptually on par with WebP q80 but
                # ~30% lighter. speed=8 keeps the (first-request) encode snappy;
                # cached on disk afterwards.
                save_kwargs = {"quality": AVIF_QUALITY, "speed": AVIF_SPEED_ONTHEFLY}
            else:
                # method=4 → fast WebP encode (was 6, which is ~10× slower on
                # large originals); near-identical size, cached on disk anyway.
                save_kwargs = {"quality": WEBP_VARIANT_QUALITY, "method": WEBP_METHOD_ONTHEFLY}
            img.save(out, format=save_fmt, **save_kwargs)
            return out.getvalue(), mime_map[target], target, True
        # Resize-only (no modern target) → keep original format, still cache.
        orig_fmt = (img.format or "JPEG")
        if orig_fmt.upper() == "JPEG" and img.mode != "RGB":
            img = img.convert("RGB")
        img.save(out, format=orig_fmt)
        return out.getvalue(), content_type, "orig", True
    except Exception as exc:
        logger.debug("img transform fallback: %s", exc)
        return data, content_type, "orig", False


@api_router.get("/files/{path:path}")
async def download_file(
    path: str,
    w: Optional[int] = None,
    fmt: Optional[str] = None,
    accept: str = Header(default=""),
):
    """Public proxy that streams an object from Emergent storage.
    Used by <img src="/api/files/..."> tags in the CMS — no auth needed
    because CMS images are part of the public site content.

    Optional on-the-fly optimisation (responsive + modern formats):
      • ?w=640        → downscale to <= 640px wide (aspect preserved)
      • ?fmt=webp     → re-encode as WebP
      • ?fmt=avif     → re-encode as AVIF
      • ?fmt=auto     → negotiate via the request Accept header
                        (WebP preferred for fast encode + broad support)
    Transformed variants are content-addressed and cached on disk, then
    served with a long immutable Cache-Control for aggressive caching.
    Passthrough (no w/fmt) keeps the original bytes — zero regression."""
    # ---- Fast path: original bytes, unchanged behaviour ----
    if not w and not fmt:
        try:
            # get_object uses blocking `requests`; offload to a thread so a
            # burst of <img> requests can't block the event loop and freeze
            # other API calls (e.g. the library search box).
            data, content_type = await asyncio.to_thread(get_object, path)
        except Exception as exc:
            logger.warning("Emergent storage fetch failed for %s: %s", path, exc)
            raise HTTPException(status_code=404, detail="File not found")
        return Response(
            content=data,
            media_type=content_type,
            headers={"Cache-Control": "public, max-age=86400"},
        )

    # ---- Resolve target format ----
    accept_l = (accept or "").lower()
    target = None
    if fmt == "avif":
        target = "avif"
    elif fmt == "webp":
        target = "webp"
    elif fmt == "auto":
        # Prefer AVIF (smallest at equal quality) when the browser advertises
        # support; variants are cached on disk, so the heavier AVIF encode is
        # paid only once. Fall back to WebP, then to the original bytes.
        if "image/avif" in accept_l:
            target = "avif"
        elif "image/webp" in accept_l:
            target = "webp"

    # ---- Snap width to a small set of buckets to maximise cache hits ----
    width = None
    if w and w > 0:
        width = next((b for b in IMG_WIDTH_BUCKETS if b >= w), IMG_WIDTH_BUCKETS[-1])

    # ---- Disk cache lookup ----
    ext = target or "orig"
    key = hashlib.sha1(f"{path}|{width}|{ext}".encode("utf-8")).hexdigest()
    cache_file = IMG_CACHE_DIR / f"{key}.{ext}"
    mime_map = {"avif": "image/avif", "webp": "image/webp"}
    # `Vary: Accept` so a shared/CDN cache (Cloudflare) never serves an AVIF
    # variant to a client that only advertised WebP (or vice-versa) on the
    # `fmt=auto` negotiated path. Harmless for explicit `fmt=avif|webp`.
    long_cache = {"Cache-Control": "public, max-age=31536000, immutable", "Vary": "Accept"}
    if cache_file.exists():
        return Response(
            content=cache_file.read_bytes(),
            media_type=mime_map.get(target, "image/jpeg"),
            headers=long_cache,
        )

    # ---- Fetch original + transform (encode off the event loop) ----
    try:
        data, content_type = await asyncio.to_thread(get_object, path)
    except Exception as exc:
        logger.warning("Emergent storage fetch failed for %s: %s", path, exc)
        raise HTTPException(status_code=404, detail="File not found")

    result, out_mime, used_ext, cacheable = await asyncio.to_thread(
        _encode_variant, data, content_type, width, target, mime_map
    )
    if not cacheable:
        # Pillow couldn't process it (SVG, corrupt, …) → original bytes, short TTL.
        return Response(
            content=result,
            media_type=out_mime,
            headers={"Cache-Control": "public, max-age=86400", "Vary": "Accept"},
        )
    # Persist the content-addressed variant for instant future hits.
    cache_file = IMG_CACHE_DIR / f"{key}.{used_ext}"
    try:
        cache_file.write_bytes(result)
    except Exception as exc:
        logger.debug("img cache write failed: %s", exc)
    return Response(content=result, media_type=out_mime, headers=long_cache)


# ---------- Image cache warm-up ----------
# Pre-generates the standard modern-format variants (LQIP + display widths in
# AVIF & WebP) for EVERY stored image, writing them to the on-disk variant
# cache. This removes the first-visit "cold encode" latency so even the very
# first visitor gets instant delivery for all imagery. Idempotent: already
# cached variants are skipped. Runs automatically (background) on startup and
# can be re-triggered from /admin after new images are added.
import multiprocessing as _mp
from concurrent.futures import ProcessPoolExecutor

# Warm-up is intentionally conservative so it can NEVER OOM / peg-CPU a
# memory-constrained container. Tune via env:
#   IMG_WARM_ON_STARTUP  → run the full batch warm-up on boot (default: ON)
#   IMG_WARM_WORKERS     → CPU worker processes (default: 1 → encodes in
#                          threads, fully sequential, no extra processes;
#                          >1 spawns a pool for faster but heavier warming)
#   IMG_WARM_THROTTLE    → seconds to pause between images (default: 0.05) so
#                          live traffic always keeps CPU headroom
def _env_flag(name, default=False):
    v = os.environ.get(name)
    if v is None:
        return default
    return v.strip().lower() in ("1", "true", "yes", "on")

WARM_ON_STARTUP = _env_flag("IMG_WARM_ON_STARTUP", False)
# Auto-shrink oversized stored masters on boot. DEFAULT OFF (manual-only):
# re-optimization is a one-time catch-up for legacy oversized masters (new
# uploads are already optimized at upload time), so running it on EVERY boot
# just risks hammering a constrained container in a loop. Run it on demand from
# the Admin panel ("Re-optimizar Biblioteca") during low traffic instead.
# Set IMG_REOPT_ON_STARTUP=true to re-enable the automatic boot run.
REOPT_ON_STARTUP = _env_flag("IMG_REOPT_ON_STARTUP", False)
try:
    _WARM_WORKERS = max(1, int(os.environ.get("IMG_WARM_WORKERS", "1")))
except (TypeError, ValueError):
    _WARM_WORKERS = 1
# Sequential by default (inflight == workers) → with 1 worker only one image is
# encoded at a time, leaving the rest of the cores free for serving requests.
_WARM_INFLIGHT = _WARM_WORKERS
try:
    _WARM_THROTTLE = max(0.0, float(os.environ.get("IMG_WARM_THROTTLE", "0.05")))
except (TypeError, ValueError):
    _WARM_THROTTLE = 0.05

# Hard memory guard: never DECODE a master larger than this during warm-up.
# A handful of un-optimised giants (e.g. raw multi-MB PNG/JPEG imported before
# import-time optimisation) can balloon to hundreds of MB once decoded to a
# raster and OOM-kill a constrained container — which takes the WHOLE backend
# down and surfaces as a Cloudflare 520 on every /api/* route (incl. the
# /api/files listing). Those giants are served on-demand instead and should be
# shrunk via the "Re-optimizar Biblioteca" backfill. Default 4 MB; tune via env.
try:
    WARM_MAX_MASTER_BYTES = max(0, int(os.environ.get("IMG_WARM_MAX_MASTER_BYTES", str(4 * 1024 * 1024))))
except (TypeError, ValueError):
    WARM_MAX_MASTER_BYTES = 4 * 1024 * 1024


def _encode_all_variants(data: bytes, specs):
    """Picklable, process-pool-safe. `specs` is a list of (width, fmt). Decodes
    the original ONCE, resizes ONCE per distinct width, and encodes every
    requested variant. Returns a list of bytes|None aligned with `specs`.
    Sending the original to the worker a single time (instead of once per
    variant) keeps IPC cheap — the CPU-bound encoding is what we parallelise."""
    results = [None] * len(specs)
    try:
        base = Image.open(BytesIO(data))
        # Reduced-scale decode hint sized to the largest requested width — a
        # big speedup for multi-MB JPEG originals (no-op for other formats).
        max_w = max((w for (w, _f) in specs if w), default=None)
        if max_w:
            try:
                base.draft(None, (max_w, max_w))
            except Exception:
                pass
        base.load()
        if base.mode not in ("RGB", "RGBA"):
            base = base.convert("RGBA" if "A" in base.getbands() else "RGB")
    except Exception:
        return results
    resized = {}
    for i, (width, fmt) in enumerate(specs):
        try:
            if width not in resized:
                im = base
                if width and base.width > width:
                    new_h = max(1, round(base.height * width / base.width))
                    im = base.resize((width, new_h), Image.LANCZOS)
                resized[width] = im
            out = BytesIO()
            if fmt == "avif":
                resized[width].save(out, format="AVIF", quality=AVIF_QUALITY, speed=AVIF_SPEED_WARM)
            else:
                resized[width].save(out, format="WEBP", quality=WEBP_VARIANT_QUALITY, method=WEBP_METHOD_WARM)
            results[i] = out.getvalue()
        except Exception:
            results[i] = None
    return results


def _missing_variants(path: str):
    """Which (width, fmt) variants for `path` are not yet on disk?
    Returns (missing[list of (width, fmt, cache_file)], already_cached_count)."""
    missing, skipped = [], 0
    for fmt in WARM_FORMATS:
        for w in WARM_WIDTHS:
            width = next((b for b in IMG_WIDTH_BUCKETS if b >= w), IMG_WIDTH_BUCKETS[-1])
            key = hashlib.sha1(f"{path}|{width}|{fmt}".encode("utf-8")).hexdigest()
            cache_file = IMG_CACHE_DIR / f"{key}.{fmt}"
            if cache_file.exists():
                skipped += 1
            else:
                missing.append((width, fmt, cache_file))
    return missing, skipped


async def _run_warm_cache():
    """Background job: warm the AVIF/WebP variant cache for every image in
    db.files, fanning the CPU-bound encoding out across worker processes so it
    finishes quickly while leaving cores free for live serving."""
    if _warm_state["running"]:
        return
    _warm_state.update({
        "running": True, "total": 0, "done": 0, "generated": 0,
        "skipped": 0, "errors": 0,
        "started_at": datetime.now(timezone.utc).isoformat(), "finished_at": None,
    })
    pool = None
    try:
        seen, uniq = set(), []
        async for d in db.files.find({}, {"storage_path": 1, "size": 1}):
            p = d.get("storage_path")
            if p and p not in seen:
                seen.add(p)
                uniq.append((p, d.get("size") or 0))
        _warm_state["total"] = len(uniq)

        loop = asyncio.get_event_loop()
        # Only spawn worker processes when explicitly configured (>1). With the
        # safe default (1) we encode in threads — no extra process memory, so a
        # constrained container can never be OOM-killed by the warm-up.
        if _WARM_WORKERS > 1:
            try:
                # `spawn` re-imports cleanly (no fork-deadlock with the running
                # event loop / Mongo sockets); workers only do CPU encoding.
                pool = ProcessPoolExecutor(max_workers=_WARM_WORKERS, mp_context=_mp.get_context("spawn"))
            except Exception as exc:
                logger.warning("warm-up process pool unavailable (%s); falling back to threads", exc)
                pool = None

        sem = asyncio.Semaphore(_WARM_INFLIGHT)

        async def _worker(p, size=0):
            async with sem:
                try:
                    # Skip memory-bomb masters so the warm-up can never OOM.
                    if WARM_MAX_MASTER_BYTES and size and size > WARM_MAX_MASTER_BYTES:
                        _warm_state["skipped"] += 1
                        return
                    missing, skipped = await asyncio.to_thread(_missing_variants, p)
                    _warm_state["skipped"] += skipped
                    if missing:
                        data, _ct = await asyncio.to_thread(get_object, p)
                        specs = [(w, f) for (w, f, _cf) in missing]
                        if pool is not None:
                            results = await loop.run_in_executor(pool, _encode_all_variants, data, specs)
                        else:
                            results = await asyncio.to_thread(_encode_all_variants, data, specs)
                        for (w, f, cf), res in zip(missing, results):
                            if isinstance(res, (bytes, bytearray)) and res:
                                try:
                                    cf.write_bytes(res)
                                    _warm_state["generated"] += 1
                                except Exception:
                                    _warm_state["errors"] += 1
                            else:
                                _warm_state["errors"] += 1
                except Exception:
                    _warm_state["errors"] += 1
                finally:
                    _warm_state["done"] += 1
            # Throttle OUTSIDE the semaphore so we never hold a slot while
            # idling — keeps CPU headroom for live image/API requests.
            if _WARM_THROTTLE:
                await asyncio.sleep(_WARM_THROTTLE)

        await asyncio.gather(*[_worker(p, size) for (p, size) in uniq])
    except Exception as exc:
        logger.error("image cache warm-up failed: %s", exc)
    finally:
        if pool is not None:
            try:
                pool.shutdown(wait=False)
            except Exception:
                pass
        _warm_state["running"] = False
        _warm_state["finished_at"] = datetime.now(timezone.utc).isoformat()
        logger.info(
            "image cache warm-up finished: total=%s generated=%s skipped=%s errors=%s",
            _warm_state["total"], _warm_state["generated"],
            _warm_state["skipped"], _warm_state["errors"],
        )


async def _warm_one_path(path: str, data=None):
    """Fire-and-forget: warm the standard AVIF/WebP variants for a SINGLE
    freshly uploaded/edited image so it is hot immediately (no first-visit
    encode). Uses the bytes already in hand when provided (no storage
    round-trip). Encoding runs in a thread so it never blocks the request."""
    try:
        missing, _skipped = await asyncio.to_thread(_missing_variants, path)
        if not missing:
            return
        if data is None:
            data, _ct = await asyncio.to_thread(get_object, path)
        # Don't decode memory-bomb masters (OOM safety) — served on-demand.
        if WARM_MAX_MASTER_BYTES and data and len(data) > WARM_MAX_MASTER_BYTES:
            return
        specs = [(w, f) for (w, f, _cf) in missing]
        results = await asyncio.to_thread(_encode_all_variants, data, specs)
        for (w, f, cf), res in zip(missing, results):
            if isinstance(res, (bytes, bytearray)) and res:
                try:
                    cf.write_bytes(res)
                except Exception:
                    pass
    except Exception as exc:
        logger.debug("post-upload warm failed for %s: %s", path, exc)


